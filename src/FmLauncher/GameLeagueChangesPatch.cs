namespace FmLauncher;

internal static class GameLeagueChangesPatch
{
    internal const int HeaderSize = 64, RowSize = 48, LogOffset = 4096;
    internal const int Capacity = 1024, LogEntrySize = 32;
    internal const int StateSize = LogOffset + Capacity * LogEntrySize;
    internal const int IdentityOffset = 3000;

    internal static byte[] Build(uint address, uint state, uint diagnostics)
    {
        var c = new NativeCode(address);
        var identityGuardIndex = 0;
        c.Emit(0x9C,0x60, 0x89,0xE5, 0x81,0xEC); c.Dword(544);
        c.Emit(0x83,0xE4,0xF0, 0x0F,0xAE,0x04,0x24);
        c.Emit(0xC7,0x84,0x24); c.Dword(512); c.Dword(0x1F80);
        c.Emit(0x0F,0xAE,0x94,0x24); c.Dword(512);
        c.Emit(0xBF); c.Dword(state);
        c.Emit(0xB8); c.Dword(1);
        c.Emit(0x87,0x47,28, 0x85,0xC0); c.Branch(0x85,"restore");
        c.Emit(0x83,0x3F,1); c.Branch(0x85,"unlock");
        c.Emit(0x83,0x7F,20,0); c.Branch(0x85,"unlock");
        GenerationGuard();
        c.Emit(0x0F,0xB7,0x1D); c.Dword(0x1B1EE16);
        c.Emit(0x3B,0x5F,12); c.Branch(0x8E,"unlock");
        c.Emit(0x89,0xD8, 0x2B,0x47,8, 0x85,0xC0); c.Branch(0x8E,"unlock");
        c.Emit(0xA8,1); c.Branch(0x85,"unlock");
        c.Emit(0x81,0x7F,16); c.Dword((uint)(Capacity - LeagueMemoryReader.TopLeagues.Length));
        c.Branch(0x87,"capacity");
        c.Emit(0x8D,0x77,HeaderSize, 0xB9); c.Dword((uint)LeagueMemoryReader.TopLeagues.Length);
        c.Mark("validate");
        c.Emit(0x8B,0x56,8, 0x8B,0x42,0x14, 0x3B,0x06); c.Branch(0x85,"invalid");
        c.Emit(0x8B,0x02, 0x3B,0x46,28); c.Branch(0x85,"invalid");
        c.Emit(0x8B,0x42,0x64, 0x3B,0x46,12); c.Branch(0x85,"invalid");
        c.Emit(0x0F,0xB7,0x82); c.Dword(0x84);
        c.Emit(0x83,0xF8,1); c.Branch(0x8C,"invalid");
        c.Emit(0x83,0xF8,20); c.Branch(0x8F,"invalid");
        c.Emit(0x89,0x46,32, 0x8B,0x56,12, 0x8B,0x42,0x14, 0x3B,0x46,4);
        c.Branch(0x85,"invalid");
        c.Emit(0x80,0xBA); c.Dword(0x1C4); c.Emit(6); c.Branch(0x85,"invalid");
        c.Emit(0x8B,0x92); c.Dword(0x1C0);
        c.Emit(0x85,0xD2); c.Branch(0x84,"invalid");
        c.Emit(0x66,0x0F,0x57,0xC0);
        for (byte i = 0; i < 5; i++)
        {
            c.Emit(0xF3,0x0F,0x5A,0x4A,(byte)(i*4));
            c.Emit(0x66,0x0F,0x2E,0x4F,56);
            c.Branch(0x8A,"invalid"); c.Branch(0x82,"invalid");
            c.Emit(0x66,0x0F,0x2E,0x4F,48); c.Branch(0x87,"invalid");
            c.Emit(0xF2,0x0F,0x58,0xC1);
        }
        c.Emit(0xF2,0x0F,0x11,0x46,40, 0xF2,0x0F,0x51,0xC0,
            0xF2,0x0F,0x5C,0x46,16, 0xF2,0x0F,0x59,0x47,32,
            0xF2,0x0F,0x2A,0x4E,24, 0xF2,0x0F,0x58,0xC1,
            0xF2,0x0F,0x58,0x47,40, 0xF2,0x0F,0x2C,0xC0);
        c.Emit(0x83,0xF8,1); c.Branch(0x8D,"minimum");
        c.Emit(0xB8); c.Dword(1);
        c.Mark("minimum");
        c.Emit(0x83,0xF8,20); c.Branch(0x8E,"target");
        c.Emit(0xB8); c.Dword(20);
        c.Mark("target");
        c.Emit(0x89,0x46,36, 0x8B,0x56,32, 0x3B,0xD0); c.Branch(0x84,"next");
        c.Branch(0x8F,"decrease");
        c.Emit(0x42); c.Jump("proposed");
        c.Mark("decrease"); c.Emit(0x4A);
        c.Mark("proposed"); c.Emit(0x89,0x56,32);
        c.Mark("next");
        c.Emit(0x83,0xC6,RowSize, 0x49); c.Branch(0x85,"validate");
        GenerationGuard();
        c.Emit(0x8D,0x77,HeaderSize, 0xB9); c.Dword((uint)LeagueMemoryReader.TopLeagues.Length);
        c.Mark("commit");
        c.Emit(0x8B,0x56,8, 0x0F,0xB7,0x82); c.Dword(0x84);
        c.Emit(0x3B,0x46,32); c.Branch(0x84,"unchanged");
        c.Emit(0x51,0x52, 0x8B,0x4F,16, 0xC1,0xE1,5, 0x8D,0x8C,0x0F); c.Dword(LogOffset);
        c.Emit(0x89,0x19, 0x8B,0x16, 0x89,0x51,4, 0x89,0x41,8,
            0x8B,0x46,32, 0x89,0x41,12, 0x8B,0x46,36, 0x89,0x41,16,
            0xF2,0x0F,0x10,0x46,40, 0xF2,0x0F,0x11,0x41,20,
            0x8B,0x47,4, 0x89,0x41,28, 0x5A, 0x66,0x8B,0x46,32,
            0x66,0x89,0x82); c.Dword(0x84);
        c.Emit(0xF0,0xFF,0x47,16, 0x59);
        c.Mark("unchanged");
        c.Emit(0x83,0xC6,RowSize, 0x49); c.Branch(0x85,"commit");
        c.Emit(0x89,0x5F,12); c.Jump("unlock");
        c.Mark("invalid");
        c.Emit(0xC7,0x47,20); c.Dword(1); c.Jump("disarm");
        c.Mark("capacity");
        c.Emit(0xC7,0x47,20); c.Dword(2);
        c.Mark("disarm");
        c.Emit(0xC7,0x07); c.Dword(0);
        c.Mark("unlock");
        c.Emit(0xC7,0x47,28); c.Dword(0);
        c.Mark("restore");
        c.Emit(0x0F,0xAE,0x0C,0x24, 0x89,0xEC, 0x61,0x9D,0xC3);
        return c.Finish();

        void GenerationGuard()
        {
            c.Emit(0xA1); c.Dword(diagnostics + 12);
            c.Emit(0x3B,0x47,4); c.Branch(0x85,"disarm");
            c.Emit(0xA1); c.Dword(diagnostics + 16);
            c.Emit(0x85,0xC0); c.Branch(0x85,"disarm");
            c.Emit(0xA1); c.Dword(diagnostics + 8);
            c.Emit(0x85,0xC0); c.Branch(0x85,"disarm");
            var label = "identity-" + identityGuardIndex++;
            c.Emit(0x83,0xBF); c.Dword(IdentityOffset + 12); c.Emit(0);
            c.Branch(0x84, label);
            foreach (var (source, offset) in new[] { (0x1911160u, 0), (0x1911168u, 4), (0x191116Cu, 8) })
            {
                if (offset == 8) c.Emit(0x0F,0xB6,0x05);
                else c.Emit(0xA1);
                c.Dword(source);
                c.Emit(0x3B,0x87); c.Dword((uint)(IdentityOffset + offset));
                c.Branch(0x85,"disarm");
            }
            c.Mark(label);
        }
    }
}
