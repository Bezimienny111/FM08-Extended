namespace FmLauncher;

internal sealed record AgingHook(uint Address, byte[] Original, byte[] Replacement);

internal static class GameAgingPatch
{
    internal const uint ThresholdAddress = 0x00A34FD8;
    internal static readonly byte[] ThresholdOriginal = [0x04, 0x1C];
    internal static readonly byte[] ThresholdDelayed = [0x04, 0x1F];
    internal static readonly AgingHook[] Hooks =
    [
        new(0xA34F7B, [0x8A,0x4C,0x24,0x13,0x3A,0xCB],
            [0x80,0xC3,3, 0x8A,0x4C,0x24,0x13,0x3A,0xCB]),
        new(0xA35616, [0x0F,0xBE,0x54,0x24,0x22,0x03,0x54,0x24,0x2C],
            [0x0F,0xBE,0x54,0x24,0x22,0x03,0x54,0x24,0x2C,0x83,0xC2,3]),
        new(0xA35630, [0x8A,0x44,0x24,0x1F,0x38,0x44,0x24,0x13,0x7E,0x20,0x8B,0x54,0x24,0x2C], []),
        new(0xA357ED, [0x03,0x44,0x24,0x2C,0x3B,0xE8],
            [0x03,0x44,0x24,0x2C,0x83,0xC0,3,0x3B,0xE8]),
        new(0xA35948, [0x8D,0x4F,3,0x3B,0xE9],
            [0x8D,0x4F,6,0x3B,0xE9]),
        new(0xA35995, [0x2B,0x6C,0x24,0x2C,0x55],
            [0x2B,0x6C,0x24,0x2C,0x83,0xED,3,0x55]),
        new(0xA359C1, [0x8D,0x57,1,0x3B,0xEA],
            [0x83,0xC7,3,0x8D,0x57,1,0x3B,0xEA]),
        new(0xA359E1, [0x8B,0x7C,0x24,0x40,0x57],
            [0x8B,0x7C,0x24,0x40,0x8D,0x47,0xFD,0x50])
    ];

    internal static byte[] Build(uint address, AgingHook hook, byte[] original)
    {
        if (!Hooks.Contains(hook) || !original.SequenceEqual(hook.Original))
            throw new LauncherException("UnexpectedGameMemory");
        var code = new NativeCode(address);
        if (hook.Address == 0xA35630)
        {
            // Preserve the physical-decline branch's shared entry at 0xA3563E.
            code.Emit(0x8A,0x44,0x24,0x1F,0x04,3,0x38,0x44,0x24,0x13);
            code.Branch(0x8E, 0xA3565Au);
            code.Emit(0x8B,0x54,0x24,0x2C,0x83,0xC2,3);
        }
        else code.Emit(hook.Replacement);
        code.Jump(hook.Address + (uint)hook.Original.Length);
        return code.Finish();
    }
}
